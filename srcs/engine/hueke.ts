// Hueke: modules are loaded by logical path, then init(root) normalizes the ledger rooted at one
// module and the modules it includes (docs/core/ledger.md). check() returns every diagnostic.

import type {
  Account,
  AccountRoot,
  Balance,
  Commodity,
  Entity,
  Id,
  LedgerSettings,
  Posting,
  Transaction,
} from "../data/model/types.js";
import { anchorKey } from "../data/raw/anchor.js";
import type { AnchorRef, ModuleData } from "../data/raw/model.js";
import { logicalPath } from "../data/source/paths.js";
import {
  position,
  type Diagnostic,
  type SourcePath,
  type SourceSpan,
} from "../data/source/source.js";
import { diagnostic } from "../data/source/diagnostics.js";
import { compareTime } from "../data/time/time.js";
import { obligationPlace } from "../data/model/account.js";
import { duplicateAnchors, resolveTags } from "./normalize/anchors.js";
import {
  collectDeclarations,
  inherit,
  makeAccount,
  type Declarations,
} from "./normalize/declarations.js";
import { collectModules } from "./normalize/modules.js";
import { expandPads } from "./normalize/pad.js";
import { buildBalance, buildTransaction, type RecordContext } from "./normalize/records.js";
import { obligationEntities, type ObligationEntities } from "./normalize/shared.js";
import { validate } from "./normalize/validate.js";

export interface HuekeOptions {
  /** Used only when the ledger has no `option timezone`. */
  readonly timezone?: string;
  /** Turns on strict mode for every kind, whatever the ledger says. */
  readonly strict?: boolean;
}

interface Internals {
  readonly diagnostics: Diagnostic[];
  readonly decimals: Map<Posting, number>;
  /** Source position of each transaction; generated ones come after every source record. */
  readonly order: Map<Transaction, number>;
  /** The entities of each obligation, collected from the whole ledger. */
  obligations: ObligationEntities;
  validated?: Diagnostic[];
}

const internals = new WeakMap<Hueke, Internals>();

/** One use of an account, commodity or entity by a record, in source order. */
interface Use {
  readonly account?: Id;
  readonly commodity?: Id;
  readonly entity?: Id;
  readonly source: SourcePath;
  readonly span: SourceSpan | undefined;
}

export class Hueke {
  // Filled in by init().
  root: SourcePath = "";
  modules: SourcePath[] = [];
  readonly data = new Map<SourcePath, ModuleData>();
  settings: LedgerSettings = {
    timezone: "UTC",
    weekStart: "monday",
    strict: [],
    decimalMark: ".",
    groupMark: ",",
  };
  roots: AccountRoot[] = [];
  accounts: Account[] = [];
  commodities: Commodity[] = [];
  entities: Entity[] = [];
  transactions: Transaction[] = []; // with the records generated by #system:
  balances: Balance[] = [];

  readonly #options: HuekeOptions;
  #initialized = false;

  constructor(options: HuekeOptions = {}) {
    this.#options = options;
  }

  /** Keeps one module's Raw model; a later load of the same path replaces it. */
  load(path: SourcePath, data: ModuleData): void {
    if (this.#initialized) throw new Error("load() after init(): create a new Hueke instead");
    this.data.set(logicalPath(path), data);
  }

  /** Normalizes the ledger rooted at `root`. */
  init(root: SourcePath): void {
    if (this.#initialized) throw new Error("init() can be called once");
    this.#initialized = true;
    root = logicalPath(root);
    this.root = root;
    const out: Diagnostic[] = [];
    const decimals = new Map<Posting, number>();
    const order = new Map<Transaction, number>();
    const inner: Internals = { diagnostics: [], decimals, order, obligations: new Map() };
    internals.set(this, inner);

    if (!this.data.has(root)) {
      inner.diagnostics.push(diagnostic("module.missing", `${root} is not loaded`, root));
      return;
    }

    // Step 1: modules
    const modules = collectModules(this.data, root, out);
    this.modules = modules.ledger;
    const where = (source: SourcePath, span: SourceSpan | undefined): string => {
      const data = this.data.get(source);
      return data && span ? `${source}:${String(position(data, span.start).line)}` : source;
    };

    // Step 2: declarations
    const declared = collectDeclarations(modules.items, root, this.#options, where, out);
    this.settings = declared.settings;
    this.roots = [...declared.roots.values()];

    // Anchors defined more than once define nothing (docs/core/anchors.md, "Anchors").
    const duplicated = duplicateAnchors(
      modules.items,
      (item) => declared.accounts.get(item.args[0] ?? "")?.span === item.span,
      where,
      out,
    );
    for (const [id, a] of declared.accounts)
      if (a.anchor !== undefined && duplicated.has(a.anchor)) {
        const rest: { -readonly [K in keyof Account]?: Account[K] } = { ...a };
        delete rest.anchor;
        declared.accounts.set(id, rest as Account);
      }
    const defines = (ref: AnchorRef): boolean => !duplicated.has(anchorKey(ref));
    const usedDecimals = new Map<Id, number>();
    const base = {
      settings: declared.settings,
      format: declared.settings,
      aliases: declared.aliases,
      time: { timezone: declared.settings.timezone, weekStart: declared.settings.weekStart },
      roots: declared.roots,
      accounts: declared.accounts,
      defines,
      out,
      decimals,
      usedDecimals,
    };

    // Steps 3 to 5: records, with inherited times and status, totals and filled-in amounts
    let auto = 0;
    let records: (Transaction | Balance)[] = [];
    let transactions: Transaction[] = [];
    const balances: Balance[] = [];
    for (const { item, source, dropped } of modules.items) {
      const ctx: RecordContext = { ...base, source };
      if (item.kind === "transaction") {
        const id =
          item.anchor && defines(item.anchor) ? anchorKey(item.anchor) : `~${String(++auto)}`;
        if (dropped) continue;
        const t = buildTransaction(item, id, ctx);
        if (!t) continue;
        transactions.push(t);
        records.push(t);
      } else if (item.kind === "balance") {
        const b = buildBalance(item, ctx);
        if (!b) continue;
        balances.push(b);
        records.push(b);
      }
    }
    // Tags and primary tags, once every record that defines an anchor is built.
    const resolved = resolveTags(transactions, declared.accounts.values(), decimals, out);
    const replaced = new Map(transactions.map((t, i) => [t, resolved[i] as Transaction]));
    records = records.map((r) => ("postings" in r ? (replaced.get(r) ?? r) : r));
    transactions = resolved;
    for (const t of transactions) order.set(t, order.size);

    // Step 6: pad balances, sorting, undeclared objects and inferred precision
    const precision = (id: Id): number =>
      settledPrecision(declared.commodities.get(id), usedDecimals.get(id));
    const generated = expandPads(
      balances,
      transactions,
      declared.settings,
      declared.accounts,
      obligationEntities(transactions, declared.accounts),
      precision,
      out,
    );
    for (const g of generated) order.set(g.transaction, order.size);
    const padded = new Map(generated.map((g) => [g.balance, g.transaction]));
    this.transactions = [...transactions, ...generated.map((g) => g.transaction)].sort(
      (a, b) => compareTime(a.effective, b.effective) || (order.get(a) ?? 0) - (order.get(b) ?? 0),
    );
    this.balances = balances;

    // Undeclared accounts and commodities are created in the order of their first use.
    const uses: Use[] = [];
    const postingUses = (t: Transaction, span?: SourceSpan): void => {
      for (const p of t.postings) {
        const at = { source: t.source, span: span ?? p.span };
        uses.push({ ...at, account: p.account, commodity: p.amount.commodity });
        for (const r of p.refs) uses.push({ ...at, entity: r.entity });
        if (p.price) uses.push({ ...at, commodity: p.price.commodity });
        if (p.cost) uses.push({ ...at, commodity: p.cost.commodity });
      }
    };
    for (const r of records) {
      if ("postings" in r) {
        for (const ref of r.refs) uses.push({ source: r.source, span: r.span, entity: ref.entity });
        postingUses(r);
        continue;
      }
      uses.push({
        source: r.source,
        span: r.span,
        account: r.account,
        commodity: r.amount.commodity,
        ...(r.entity !== undefined && { entity: r.entity }),
      });
      const pad = padded.get(r);
      if (pad) postingUses(pad, r.span);
    }
    const objects = this.#resolve(declared, usedDecimals, uses, out);
    this.commodities = [...objects.commodities.values()];
    this.accounts = [...objects.accounts.values()];
    this.entities = [...objects.entities.values()];
    inner.obligations = obligationEntities(this.transactions, objects.accounts);
    // The merged root must not be a root that accounts already use, declared or not.
    const merged = this.settings.incomeExpenseRoot;
    if (merged !== undefined && this.accounts.some((a) => a.id.split(":")[0] === merged)) {
      const at = declared.incomeExpenseAt;
      out.push(
        diagnostic(
          "option.invalid-root",
          `${merged} is already a root of accounts`,
          at?.source,
          at?.span,
        ),
      );
      const settings: { -readonly [K in keyof LedgerSettings]?: LedgerSettings[K] } = {
        ...this.settings,
      };
      delete settings.incomeExpenseRoot;
      this.settings = settings as LedgerSettings;
    }
    inner.diagnostics.push(...modules.parsed, ...out);
  }

  /** Creates undeclared accounts and commodities, each after the declared ones, as first used. */
  #resolve(
    declared: Declarations,
    usedDecimals: ReadonlyMap<Id, number>,
    uses: readonly Use[],
    out: Diagnostic[],
  ): {
    commodities: Map<Id, Commodity>;
    accounts: Map<Id, Account>;
    entities: Map<Id, Entity>;
  } {
    const strictCommodity = this.settings.strict.includes("commodity");
    const strictAccount = this.settings.strict.includes("account");
    const strictEntity = this.settings.strict.includes("entity");
    const entities = new Map(declared.entities);
    const commodities = new Map<Id, Commodity>();
    for (const [id, c] of declared.commodities)
      commodities.set(
        id,
        c.precisionWritten ? c : { ...c, precision: settledPrecision(c, usedDecimals.get(id)) },
      );
    const accounts = new Map(declared.accounts);
    const known = (id: Id): boolean => declared.roots.has(id.split(":")[0] ?? "");
    if (strictAccount)
      for (const a of declared.accounts.values())
        if (!known(a.id))
          out.push(
            diagnostic(
              "strict.unknown-root",
              `the root of ${a.id} is not a known root`,
              declared.sources.get(a),
              a.span,
            ),
          );

    const reported = new Set<Id>();
    for (const { account, commodity, entity, source, span } of uses) {
      if (entity !== undefined && !entities.has(entity)) {
        entities.set(entity, { id: entity, meta: {} });
        if (strictEntity)
          out.push(
            diagnostic("strict.undeclared", `entity ${entity} is not declared`, source, span),
          );
      }
      if (account !== undefined) {
        if (!accounts.has(account)) {
          accounts.set(account, inherit(makeAccount(account, declared.roots), declared.accounts));
          // An account inside an obligation account counts as declared.
          const place = obligationPlace(account, declared.accounts);
          if (strictAccount && !place)
            out.push(
              diagnostic("strict.undeclared", `account ${account} is not declared`, source, span),
            );
        }
        if (!strictAccount && !known(account) && !reported.has(account)) {
          reported.add(account);
          out.push(
            diagnostic(
              "name.unknown-root",
              `${account}: "${account.split(":")[0] ?? ""}" is not a known root`,
              source,
              span,
            ),
          );
        }
      }
      if (commodity === undefined || commodity === "" || commodities.has(commodity)) continue;
      commodities.set(commodity, {
        id: commodity,
        item: false,
        precision: usedDecimals.get(commodity) ?? 0,
        precisionWritten: false,
        aliases: [],
        meta: {},
      });
      out.push(
        strictCommodity
          ? diagnostic("strict.undeclared", `commodity ${commodity} is not declared`, source, span)
          : diagnostic(
              "name.inferred-commodity",
              `commodity ${commodity} is not declared: its precision is inferred`,
              source,
              span,
            ),
      );
    }
    return { commodities, accounts, entities };
  }
}

/** Every diagnostic of the ledger: parse, init and the step-7 checks (run once, on first call). */
export function check(hueke: Hueke): Diagnostic[] {
  const inner = internals.get(hueke);
  if (!inner) throw new Error("check() before init()");
  inner.validated ??= validate({
    transactions: hueke.transactions,
    balances: hueke.balances,
    commodities: new Map(hueke.commodities.map((c) => [c.id, c])),
    accounts: new Map(hueke.accounts.map((a) => [a.id, a])),
    obligations: inner.obligations,
    decimals: inner.decimals,
  });
  return [...inner.diagnostics, ...inner.validated];
}

/** A commodity's precision as #resolve settles it: declared, else inferred from the loaded records. */
function settledPrecision(c: Commodity | undefined, decimals: number | undefined): number {
  return c?.precisionWritten ? c.precision : (decimals ?? 0);
}

/**
 * The source position of a transaction, for ordering ties: generated transactions come after
 * every source record (docs/core/transactions.md, "Order of transactions"). Internal to Core.
 */
export function sourceOrder(hueke: Hueke): (t: Transaction) => number {
  const order = internals.get(hueke)?.order;
  return (t) => order?.get(t) ?? 0;
}

/** The entities of each obligation, by its account ID. Internal to Core. */
export function obligationEntitiesOf(hueke: Hueke): ObligationEntities {
  return internals.get(hueke)?.obligations ?? new Map();
}

/** Whether init() has run. Internal to Core. */
export function initialized(hueke: Hueke): boolean {
  return internals.has(hueke);
}
